import { pool } from "../config/db";
import type { PoolClient } from "pg";
import { ApiError } from "../utils/ApiError";
import { parseYearStartOrNull } from "../utils/assessmentYear";
import type { DemandNoticeRow } from "../repositories/demandNotice.repository";
import type { PropertyRow } from "../types/property.types";

/**
 * The last year this holding has actually paid for: the larger of its tax_paid_till_year and the year covered by any
 * settled notice whose receipt is still valid. The second is a safety net - if tax_paid_till_year was ever left behind
 * (an import, an old bug), a year already paid must still not be billed or collected again.
 */
export async function effectivePaidTillStart(property: Pick<PropertyRow, "holding_no" | "tax_paid_till_year">): Promise<number | null> {
  const stored = parseYearStartOrNull(property.tax_paid_till_year);
  const { rows } = await pool.query<{ y: number | null }>(
    `SELECT MAX(CAST(LEFT(CASE WHEN n.part_payment AND n.paid_through_year IS NOT NULL THEN n.paid_through_year ELSE n.assessment_year END, 4) AS INTEGER)) AS y
       FROM demand_notices n
       JOIN transactions t ON t.receipt_no = n.settled_receipt_no
      WHERE n.holding_no = $1 AND n.settled AND NOT n.cancelled
        AND NOT COALESCE(t.cancelled, FALSE) AND t.status = 'success'
        AND (CASE WHEN n.part_payment AND n.paid_through_year IS NOT NULL THEN n.paid_through_year ELSE n.assessment_year END) ~ '^[0-9]{4}'`,
    [property.holding_no],
  );
  const fromNotices = rows[0]?.y ?? null;
  if (stored === null) return fromNotices;
  if (fromNotices === null) return stored;
  return Math.max(stored, fromNotices);
}

const fy = (y: number) => `${y}-${y + 1}`;

/**
 * Refuses to collect on a full (non-part) demand notice whose year this holding has already paid for. Part-payment
 * notices have their own check in submitPayment. `strict` (counter / Tax Collector / agency and online initiation) also
 * refuses a notice raised for an earlier financial year: it charges that year as "current", so a fresh notice is due.
 */
export async function assertNoticeYearNotPaid(
  property: Pick<PropertyRow, "holding_no" | "tax_paid_till_year" | "assessment_year">,
  notice: Pick<DemandNoticeRow, "demand_no" | "assessment_year" | "part_payment" | "paid_through_year">,
  strict: boolean,
): Promise<void> {
  if (notice.part_payment && notice.paid_through_year) return;
  const noticeYear = parseYearStartOrNull(notice.assessment_year);
  if (noticeYear === null) return;
  const paidTill = await effectivePaidTillStart(property);
  if (paidTill !== null && paidTill >= noticeYear) {
    // An open notice (not superseded - that is refused before this) for a year already paid was raised by mistake.
    await markWronglyGenerated(notice.demand_no, fy(paidTill));
    throw ApiError.badRequest(
      `Demand notice ${notice.demand_no} (${fy(noticeYear)}) was generated by mistake - Holding No ${property.holding_no} has already paid its tax till ${fy(paidTill)}. It is marked "wrongly generated" and no payment can be taken against it.`,
    );
  }
  const currentYear = parseYearStartOrNull(property.assessment_year);
  if (strict && currentYear !== null && noticeYear < currentYear) {
    throw ApiError.badRequest(
      `Demand notice ${notice.demand_no} was raised for ${fy(noticeYear)}; the current year is ${fy(currentYear)}. Generate a fresh demand notice and collect against that.`,
    );
  }
}

/**
 * After a payment, any other notice of the holding still open is out of date (it demands years / an amount that are
 * now wrong) - it is superseded so it can never be paid. A notice on hold (cheque/DD awaiting clearance) is left alone.
 */
export async function supersedeOtherOpenNotices(holdingNo: string, paidDemandNo: string, client: PoolClient): Promise<void> {
  await client.query(
    `UPDATE demand_notices SET superseded = TRUE
      WHERE holding_no = $1 AND demand_no <> $2 AND NOT settled AND NOT cancelled AND NOT superseded AND NOT on_hold`,
    [holdingNo, paidDemandNo],
  );
}

/** The property with tax_paid_till_year raised to the last year actually paid (unchanged when they already agree). */
export async function withEffectivePaidTill<T extends Pick<PropertyRow, "holding_no" | "tax_paid_till_year">>(property: T): Promise<T> {
  const paid = await effectivePaidTillStart(property);
  if (paid === null || paid === parseYearStartOrNull(property.tax_paid_till_year)) return property;
  return { ...property, tax_paid_till_year: fy(paid) };
}

/** Marks an unpaid notice as wrongly generated (the year it demands was already paid): cancelled, with the reason. */
export async function markWronglyGenerated(demandNo: string, paidTillLabel: string): Promise<void> {
  await pool.query(
    `UPDATE demand_notices
        SET wrongly_generated = TRUE, cancelled = TRUE, cancelled_at = now(),
            cancelled_reason = 'Wrongly generated: tax of this holding was already paid till ' || $2 || '. Not payable.'
      WHERE demand_no = $1 AND NOT settled AND NOT cancelled AND NOT on_hold`,
    [demandNo, paidTillLabel],
  );
}
